#Function to make the chunked texts
def chunk_dataframe(df, max_chars=800): #each chunk with a max of 800 characters
    snippets = []

    for idx, row in df.iterrows():
        doc_id = row['file_name']

        #Getting rid of extra whitespace
        text = re.sub(r'\s+', ' ', row['text']).strip()

        #Splitting text into sentences
        sentences = sent_tokenize(text)

        #Initalizing string
        chunk, chunk_id = "", 0
        #Looping through each sentence
        for sentence in sentences:
            #Checking if adding this sentence will still stay in the max char limit
            if len(chunk) + len(sentence) <= max_chars:
                #Adding sentence to current chunk
                chunk += " " + sentence
            #Adding information to snippit list when the chunk reaches max char limit
            else:
                snippets.append({
                    'doc_id': doc_id,
                    'chunk_id': chunk_id,
                    'text': chunk.strip()
                })
                #Adding one to chunk id
                chunk_id += 1
                #starting new chunk
                chunk = sentence
        #Outside the loop if there are extra sentences
        if chunk:
            #Saving final sentences to list
            snippets.append({
                'doc_id': doc_id,
                'chunk_id': chunk_id,
                'text': chunk.strip()
            })
    #Returning data frame with chunk information
    return pd.DataFrame(snippets)

#Chunking the df and saving it to a variable
chunked_df = chunk_dataframe(df)

