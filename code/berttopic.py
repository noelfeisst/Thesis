#Creating a function to gather all the topic snippets
# n is the number of snippets to sample
#Min_prob is the min probability threshold
#Seed is to keep it reproducable
def sample_snippets_by_topic(docs_info, topic_number=None, n=10, min_prob=0.0, seed=42):
    random.seed(seed)
    #Making a copy of the input data frame so the original doesnt change
    df = docs_info.copy()

    if topic_number is not None:
        #Keep only the rows with the corresponding topic number
        df = df[df['Topic'] == topic_number]
    #keeps rows with the correct probability
    df = df[df['Probability'] >= min_prob]

    #Randomly sample a set of rows
    sample_indices = random.sample(list(df.index), min(n, len(df)))

    #Return the randomly sampled rows with only these columns as a DF and reset the index
    return df.loc[sample_indices][['Document', 'Topic', 'Probability']].reset_index(drop=True)

